function [lhs, rhs] = static_resid(y, x, params)
T = NaN(5, 1);
lhs = NaN(12, 1);
rhs = NaN(12, 1);
T(1) = y(1)^params(6);
T(2) = y(5)^params(7);
T(3) = y(5)^(1-params(1));
T(4) = y(5)^(-params(1));
T(5) = 1/params(2)*y(3)^params(8)*exp(y(9));
lhs(1) = y(2);
rhs(1) = T(1)*T(2);
lhs(2) = y(11);
rhs(2) = params(2)/y(3);
lhs(3) = y(6);
rhs(3) = 1/y(11);
lhs(4) = y(8);
rhs(4) = y(4)*T(3);
lhs(5) = y(2);
rhs(5) = y(4)*(1-params(1))*T(4);
lhs(6) = y(6);
rhs(6) = y(3)*y(7);
lhs(7) = y(6);
rhs(7) = T(5);
lhs(8) = y(1);
rhs(8) = y(8);
lhs(9) = log(y(4));
rhs(9) = log(y(4))*params(3)+x(1);
lhs(10) = log(y(12));
rhs(10) = log(y(12))*params(4)+x(2);
lhs(11) = y(9);
rhs(11) = y(9)*params(5)+x(3);
lhs(12) = y(10);
rhs(12) = 4*log(y(3));
end
